  toggleAudioSettings(): void {
    if (this.audioPopover) {
      this.audioPopover.destroy();
      this.audioPopover = null;
      return;
    }
    const am = AudioManager.inst;
    const c = (this.audioPopover = this.scene.add.container(0, 0));
    const W = 240;
    const H = 150;
    const px = Viewport.w - 14 - W;
    const py = 56;
    c.setDepth(130);
    c.add(panelShape(this.scene, px + W / 2, py + H / 2, W, H));
    c.add(label(this.scene, px + W / 2, py + 20, "AUDIO", { size: 12, display: true, color: HEX.brass, origin: 0.5, spacing: 2 }));

    this.audioSx = px + 80;
    this.audioSw = 110;

    const musicRow = (): void => {
      const y = py + 52;
      c.add(label(this.scene, px + 16, y, "MUSIC", { size: 9, color: HEX.parchment, origin: { x: 0, y: 0.5 } }));
      const g = this.scene.add.graphics();
      g.fillStyle(0x000000, 0.4);
      g.fillRoundedRect(this.audioSx, y - 3, this.audioSw, 6, 3);
      g.fillStyle(C.brass, 1);
      g.fillRoundedRect(this.audioSx, y - 3, Math.max(4, this.audioSw * am.musicVolume), 6, 3);
      g.fillStyle(C.ivory, 1);
      g.fillCircle(this.audioSx + this.audioSw * am.musicVolume, y, 5);
      c.add(g);
      c.add(label(this.scene, px + W - 16, y, `${Math.round(am.musicVolume * 100)}%`, { size: 9, mono: true, color: HEX.muted, origin: { x: 1, y: 0.5 } }));
      const hit = this.scene.add.rectangle(this.audioSx + this.audioSw / 2, y, this.audioSw + 16, 22, 0xffffff, 0.001);
      hit.setInteractive({ useHandCursor: true });
      hit.on("pointerdown", (_p: Phaser.Input.Pointer, lx: number) => {
        this.audioDragging = "music";
        am.setMusicVolume(Phaser.Math.Clamp(0.5 + lx / this.audioSw, 0, 1));
        this.rebuildAudioPopover();
      });
      hit.on("pointermove", (_p: Phaser.Input.Pointer, lx: number) => {
        if (this.audioDragging === "music") {
          am.setMusicVolume(Phaser.Math.Clamp(0.5 + lx / this.audioSw, 0, 1));
          this.rebuildAudioPopover();
        }
      });
      c.add(hit);
    };

    const sfxRow = (): void => {
      const y = py + 88;
      c.add(label(this.scene, px + 16, y, "SOUND", { size: 9, color: HEX.parchment, origin: { x: 0, y: 0.5 } }));
      const g = this.scene.add.graphics();
      g.fillStyle(0x000000, 0.4);
      g.fillRoundedRect(this.audioSx, y - 3, this.audioSw, 6, 3);
      g.fillStyle(C.brass, 1);
      g.fillRoundedRect(this.audioSx, y - 3, Math.max(4, this.audioSw * am.sfxVolume), 6, 3);
      g.fillStyle(C.ivory, 1);
      g.fillCircle(this.audioSx + this.audioSw * am.sfxVolume, y, 5);
      c.add(g);
      c.add(label(this.scene, px + W - 16, y, `${Math.round(am.sfxVolume * 100)}%`, { size: 9, mono: true, color: HEX.muted, origin: { x: 1, y: 0.5 } }));
      const hit = this.scene.add.rectangle(this.audioSx + this.audioSw / 2, y, this.audioSw + 16, 22, 0xffffff, 0.001);
      hit.setInteractive({ useHandCursor: true });
      hit.on("pointerdown", (_p: Phaser.Input.Pointer, lx: number) => {
        this.audioDragging = "sfx";
        am.setSfxVolume(Phaser.Math.Clamp(0.5 + lx / this.audioSw, 0, 1));
        this.rebuildAudioPopover();
      });
      hit.on("pointermove", (_p: Phaser.Input.Pointer, lx: number) => {
        if (this.audioDragging === "sfx") {
          am.setSfxVolume(Phaser.Math.Clamp(0.5 + lx / this.audioSw, 0, 1));
          this.rebuildAudioPopover();
        }
      });
      c.add(hit);
    };

    musicRow();
    sfxRow();

    const muteBtn = label(this.scene, px + W / 2, py + 124, am.muted ? "SOUND OFF \u2014 click to enable" : "SOUND ON \u2014 click to mute", {
      size: 9.5,
      mono: true,
      color: am.muted ? HEX.bad : HEX.good,
      origin: 0.5,
    });
    muteBtn.setInteractive({ useHandCursor: true });
    muteBtn.on("pointerdown", () => {
      am.setMuted(!am.muted);
      this.rebuildAudioPopover();
    });
    c.add(muteBtn);
  }

  closeAudioPopover(): void {
    this.audioPopover?.destroy();
    this.audioPopover = null;
  }

  rebuildAudioPopover(): void {
    if (!this.audioPopover) return;
    this.closeAudioPopover();
    this.toggleAudioSettings();
  }

